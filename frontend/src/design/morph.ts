// 带扩展名：本文件会被 scripts/check-motion.mjs 以「类型擦除」方式直接导入，
// 走的是 Node 的 ESM 解析，不能像打包器那样省略后缀
import { ICON_VIEWBOX } from './icons.ts'

/**
 * 「更多」按钮的图标形变参数 —— **归档**。
 *
 * 形变过程：三个圆点 → 连成一条横线 → 整体转 90° 变成竖杆 → 顶端展出箭头 ↑。
 * 这套坐标是手调的，**两个状态都必须绕视图中心，否则转 90° 的那一瞬间图标会跳一下**，
 * 而这一跳在 0.3s 的动画里非常显眼。因为值得留，「更多」升格成一个页面、按钮不再形变
 * 之后，这些参数被挪到这里存档，而不是就地删掉。
 *
 * 当前**没有运行时调用方**，只有 `scripts/check-motion.mjs` 拿它做断言 ——
 * 这样这份坐标不会被无声改坏，将来要复用（比如真做一个折叠菜单）直接拿去就能用。
 * 收起态那三个点（DOTS_CLOSED）的形状被 `design/icons.ts` 的 `more` 图标复刻，
 * 所以第四个按钮的字形与旧版「更多」按钮是同一个。
 *
 * 改动时必须同时满足五条：
 *   1. 收起态三点的整体包围盒中心 = 视图中心；
 *   2. 展开态并入的那条线的包围盒中心 = 视图中心；
 *   3. 方块纵向中心 = 视图中心（转 90° 后就靠它对齐）；
 *   4. 展开态相邻两段必须**重叠** —— 只相切时抗锯齿会在接缝处留一道半透明缝，
 *      看着仍是三个方块而不是一条线；同色不透明矩形重叠不会变深；
 *   5. 箭头顶点 = 箭头的缩放原点 = 视图中轴。
 *
 * `scripts/check-motion.mjs` 里逐条锁着这五条，改坏了会直接构建失败。
 */

const CENTER = ICON_VIEWBOX / 2

/** 方块的纵向位置 */
export const DOTS_Y = 10.3

/** 方块高度（两个状态共用）：加上 DOTS_Y 正好是视图中心 */
export const DOTS_HEIGHT = 3.4

/** 收起态：三个等距圆角方块，靠间隙读出「…」。等距是必须的，不然读不出省略号 */
export const DOTS_CLOSED = { x: [3, 10.3, 17.6], width: 3.4, rx: 1.7 }

/** 展开态：圆角归零、相邻段重叠 2.25 单位（≈1px CSS），融成**一条完整的线**。
    重叠要够大：只相切时接缝会露缝，高分屏（dpr≥2）下 1px 的重叠才稳定盖住。
    整条线仍是 3→21，中心 12 */
export const DOTS_OPEN = { x: [3, 8.25, 13.5], width: 7.5, rx: 0 }

/** 旋转原点 = 视图中心；转 90° 后横线变竖线，充当箭头杆 */
export const STEM_ORIGIN = `${CENTER} ${CENTER}`

/** 箭头两撇：由顶点向两侧展开 */
export const HEAD_PATH = 'M5.5 10 L12 3.5 L18.5 10'

/** 箭头两撇的缩放原点 = 箭头顶点。不是顶点的话，展开时会连顶点一起位移，看着像「飘」起来 */
export const HEAD_ORIGIN = `${CENTER} 3.5`
